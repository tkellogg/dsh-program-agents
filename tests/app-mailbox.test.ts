import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, readdirSync, realpathSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { MessageStore } from '../src/app/mailbox.js';
import { ProgramError } from '../src/app/index.js';
const scope = { ownerId: 'owner', program: 'app', claimant: 'run:1' };
const hasCode = (code: string) => (error: unknown) => error instanceof ProgramError && error.code === code;

test('inbox acceptance, claims, explicit ack, and leases have distinct durable receipts', async (t) => {
  let now = Date.now();
  const store = new MessageStore(':memory:', { clock: () => now });
  t.after(() => store.close());
  const accepted = store.send(scope, { from: 'child-agent', body: { work: 1 }, correlationId: 'request' });
  assert.equal(accepted.status, 'accepted');
  assert.equal(accepted.attempts, 0);
  const message = await store.receive(scope, { leaseMs: 100 });
  assert.ok(message);
  assert.deepEqual(message.body, { work: 1 });
  assert.equal(message.from, 'child-agent');
  assert.equal(message.correlationId, 'request');
  assert.equal(message.receipt.status, 'claimed');
  assert.equal(message.receipt.attempts, 1);
  assert.equal(await store.receive(scope), null);
  assert.throws(() => store.ack(scope, message.id, 'wrong'), hasCode('LEASE_LOST'));
  assert.throws(() => store.ack({ ...scope, claimant: 'run:2' }, message.id, message.leaseToken), hasCode('LEASE_LOST'));
  const negative = store.nack(scope, message.id, message.leaseToken);
  assert.equal(negative.status, 'accepted');
  const retry = await store.receive(scope, { leaseMs: 100 });
  assert.ok(retry);
  assert.notEqual(retry.leaseToken, message.leaseToken);
  assert.equal(retry.receipt.attempts, 2);
  assert.throws(() => store.ack(scope, message.id, message.leaseToken), hasCode('LEASE_LOST'));
  now += 101;
  assert.equal(store.receipt(scope, accepted.id)?.status, 'accepted');
  assert.throws(() => store.ack(scope, retry.id, retry.leaseToken), hasCode('LEASE_LOST'));
  const reclaimed = await store.receive(scope);
  assert.ok(reclaimed);
  const ack = store.ack(scope, reclaimed.id, reclaimed.leaseToken);
  assert.equal(ack.status, 'acked');
  assert.equal(ack.attempts, 3);
  assert.ok(ack.ackedAt);
  assert.equal(await store.receive(scope), null);
  assert.throws(() => store.ack(scope, reclaimed.id, reclaimed.leaseToken), hasCode('LEASE_LOST'));
});

test('store persists across host recreation, isolates owner/program, and releases revoked claims', async (t) => {
  const directory = realpathSync(mkdtempSync(join(tmpdir(), 'dsh-app-mailbox-')));
  t.after(() => {
    assert.equal(realpathSync(directory), directory);
    assert.ok(directory.startsWith(`${realpathSync(tmpdir())}/dsh-app-mailbox-`));
    rmSync(directory, { recursive: true, force: true });
  });
  const file = join(directory, 'mailbox.sqlite');
  const first = new MessageStore(file);
  const accepted = first.send(scope, { from: 'parent', body: 'durable' });
  const claimed = await first.receive(scope);
  assert.ok(claimed);
  first.close();
  const second = new MessageStore(file);
  t.after(() => second.close());
  assert.equal(statSync(file).mode & 0o777, 0o600);
  for (const entry of readdirSync(directory).filter((name) => name.startsWith('mailbox.sqlite-'))) assert.equal(statSync(join(directory, entry)).mode & 0o777, 0o600);
  assert.equal(second.receipt(scope, accepted.id)?.status, 'claimed');
  assert.equal(second.receipt({ ownerId: 'other', program: 'app' }, accepted.id), null);
  assert.equal(second.receipt({ ownerId: 'owner', program: 'other' }, accepted.id), null);
  assert.equal(await second.receive({ ownerId: 'other', program: 'app' }), null);
  second.releaseClaims({ ...scope, claimant: 'wrong' });
  assert.equal(await second.receive(scope), null);
  second.releaseClaims(scope);
  const next = await second.receive({ ...scope, claimant: 'run:2' });
  assert.ok(next);
  assert.equal(next.id, accepted.id);
  assert.notEqual(next.leaseToken, claimed.leaseToken);
  assert.throws(() => second.ack(scope, claimed.id, claimed.leaseToken), hasCode('LEASE_LOST'));
  assert.equal(second.ack({ ...scope, claimant: 'run:2' }, next.id, next.leaseToken).status, 'acked');
});

test('concurrent receive is single-claim, bounded long polling works, and cancellation is prompt', async (t) => {
  const store = new MessageStore(':memory:');
  t.after(() => store.close());
  store.send(scope, { from: 'parent', body: 'one' });
  const values = await Promise.all([store.receive(scope), store.receive({ ...scope, claimant: 'other' })]);
  assert.equal(values.filter(Boolean).length, 1);
  const waiting = store.receive(scope, { waitMs: 1000 });
  const accepted = store.send(scope, { from: 'parent', body: 'two' });
  assert.equal((await waiting)?.id, accepted.id);
  const controller = new AbortController();
  const cancelled = store.receive(scope, { waitMs: 30000 }, controller.signal);
  controller.abort();
  await assert.rejects(cancelled, hasCode('CANCELLED'));
  await assert.rejects(store.receive(scope, { waitMs: 30001 }), hasCode('INVALID_INPUT'));
  await assert.rejects(store.receive(scope, { leaseMs: 300001 }), hasCode('INVALID_INPUT'));
});

test('queue and receipt retention are bounded; acked history can be reclaimed, not pending work', async (t) => {
  const store = new MessageStore(':memory:', { maxPendingPerProgram: 1, maxMessages: 2 });
  t.after(() => store.close());
  const first = store.send(scope, { from: 'parent', body: 'first' });
  assert.throws(() => store.send(scope, { from: 'parent', body: 'overflow' }), hasCode('BACKPRESSURE'));
  const receive = await store.receive(scope);
  assert.ok(receive);
  store.ack(scope, receive.id, receive.leaseToken);
  const secondScope = { ownerId: 'owner', program: 'second' };
  store.send(secondScope, { from: 'parent', body: 'second' });
  store.send(scope, { from: 'parent', body: 'third' });
  assert.equal(store.receipt(scope, first.id), null);
  assert.throws(() => store.send({ ownerId: 'owner', program: 'third' }, { from: 'parent', body: 'full' }), hasCode('BACKPRESSURE'));
});
